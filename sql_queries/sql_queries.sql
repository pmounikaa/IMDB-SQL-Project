-- Questions k) to m)

-- k) Which movie(s) were directed by Brenda Chapman?
SELECT m.title
FROM movies m
JOIN directors d ON m.id = d.id
WHERE d.name = 'Brenda Chapman';

-- l) Which director made the most movies?
SELECT d.name, COUNT(*) AS movie_count
FROM movies m
JOIN directors d ON m.id = d.id
GROUP BY d.id, d.name
HAVING COUNT(*) = (SELECT MAX(c) FROM (SELECT COUNT(*) AS c FROM movies GROUP BY id) t)
ORDER BY d.name;

-- m) Which director is the most bankable?
SELECT d.name, SUM(m.revenue) AS total_revenue, SUM(m.revenue - m.budget) AS total_profit
FROM movies m
JOIN directors d ON m.id = d.id
GROUP BY d.id, d.name
ORDER BY total_revenue DESC
LIMIT 1;

